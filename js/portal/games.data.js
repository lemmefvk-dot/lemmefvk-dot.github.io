/* ============================================================
   games.data.js — the games index behind static://games.

   data/games.json is generated by tools/sync-games.mjs from the
   live feeds (gamedistribution, crazygames, gamemonetize,
   gamepix) plus the curated madkid shelf. It is ~5,900 rows and
   4 MB, so everything here is built for one job: answer a
   filtered, sorted, paged question about that catalogue fast
   enough that a school Chromebook never drops a frame.

   Three deliberate choices:

     · Rows are sorted ONCE per sort key and memoised. Filtering a
       pre-sorted array keeps it sorted, so no query after the
       first ever re-sorts 5,900 rows.
     · The lowercase search haystack is built per row on first
       search, not at load — opening the page costs nothing.
     · `hasStats` is the honesty flag. No feed reports measured
       plays or ratings, so every row arrives with 0 and hasStats
       is false; nothing renders a figure unless a source with
       real numbers is added and fills them in.

   The static GAMES array in catalog.js stays the instant,
   always-available fallback: if the JSON is missing or a fetch
   fails, the portal still opens with the curated shelf.
   ============================================================ */
import { GAMES as STATIC, GAME_CATEGORIES } from './catalog.js';
import { createIndex } from '../core/fuzzy.js';

const URL_PATH = 'data/games.json';
let cache = null;
let inflight = null;
let failed = null;
let failedAt = 0;
/* true once `cache` is data/games.json. A read before load() (all(), byId()…)
   fills `cache` with the built-in shelf; that must not stop load() fetching. */
let full = false;
/* after a failed fetch, the next load() tries again once this much has passed */
const RETRY_MS = 15000;

/* derived, all invalidated together whenever `cache` is replaced */
let index = null;
let countCache = null;
let catCache = null;
let statCache = null;
let fuzzyIx = null;
const sortCache = new Map();

function dataUrl() {
  const base = new URL('../../', import.meta.url).href;
  return new URL(URL_PATH, base).href;
}

function adopt(rows) {
  cache = rows;
  index = new Map();
  for (const g of rows) index.set(g.id, g);
  countCache = null;
  catCache = null;
  statCache = null;
  fuzzyIx = null;
  sortCache.clear();
  return cache;
}

export async function load() {
  if (full) return cache;
  if (failed && Date.now() - failedAt < RETRY_MS) return cache;
  if (inflight) return inflight;
  /* a retry skips the HTTP cache, in case the copy there is what failed */
  const mode = failed ? 'reload' : 'force-cache';
  inflight = (async () => {
    const res = await fetch(`${dataUrl()}`, { cache: mode });
    if (!res.ok) throw new Error(`games catalogue: HTTP ${res.status}`);
    const rows = await res.json();
    if (!Array.isArray(rows) || !rows.length) throw new Error('games catalogue is empty');
    seq = 0;
    adopt(rows.map(normalise));
    full = true;
    failed = null;
    return cache;
  })();
  try {
    return await inflight;
  } catch (err) {
    failed = err;
    failedAt = Date.now();
    if (!cache) adopt(STATIC.map(normalise));      // degrade to the curated shelf
    return cache;
  } finally {
    inflight = null;
  }
}

let seq = 0;

/* Some feeds send titles and descriptions HTML-escaped ("Paint &amp; Escape",
   "Caf&eacute;"). Everything here is shown as text, so decode them once, at load. */
const ENTITIES = {
  amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', rsquo: '’', lsquo: '‘',
  rdquo: '”', ldquo: '“', mdash: '—', ndash: '–', hellip: '…', bull: '•',
  middot: '·', times: '×', rarr: '→', deg: '°', infin: '∞', laquo: '«',
  raquo: '»', iexcl: '¡', zwj: '‍', zwnj: '‌', eacute: 'é', egrave: 'è',
  aacute: 'á', iacute: 'í', uacute: 'ú', ouml: 'ö', uuml: 'ü', ntilde: 'ñ',
};
const decode = s => (typeof s === 'string' && s.includes('&')
  ? s.replace(/&(#\d+|#x[0-9a-f]+|[a-z]+);/gi, (m, e) => {
    if (e[0] !== '#') return ENTITIES[e.toLowerCase()] ?? m;
    const n = e[1] === 'x' || e[1] === 'X' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
    return n > 0 && n <= 0x10ffff ? String.fromCodePoint(n) : m;
  })
  : s);
/* a title also loses zero-width characters, which only push it to the top of A–Z */
const cleanTitle = s => (typeof s === 'string' ? decode(s).replace(/[​-‍﻿]/g, '').trim() : s);

function normalise(g) {
  /* The feeds that report metrics report BOTH plays and rating; the ones that
     do not send plays 0 and let the sync fill rating in. So one flag covers
     both, and nothing downstream has to guess which numbers are real. */
  const plays = Number(g.plays) || 0;
  return {
    id: g.id, kind: 'game', title: cleanTitle(g.title),
    source: g.source || g.host || 'madkid',
    studio: g.studio || SOURCE_LABEL[g.source] || 'madkidgames.com',
    embed: g.embed, open: g.open || g.embed, art: g.art || null,
    /* the same game on other networks — the player's extra servers */
    alts: Array.isArray(g.alts) ? g.alts.filter(x => x && x.embed) : [],
    cats: Array.isArray(g.cats) && g.cats.length ? g.cats : ['action'],
    tags: Array.isArray(g.tags) ? g.tags : [],
    desc: decode(g.desc || ''), note: decode(g.note || ''),
    plays, rating: Number(g.rating) || 0, hasStats: plays > 0,
    curated: g.curated === true || (g.cats || []).includes('featured'),
    /* ISO date, only if a future sync starts stamping one — see hasAdded() */
    added: typeof g.added === 'string' ? g.added : null,
    order: seq++,
    w: g.w || null, h: g.h || null,
    playable: true,
    /* filled in on first search; declared here so all 5,900 rows keep one
       hidden class instead of transitioning as the index warms up */
    hay: undefined, tlow: undefined,
  };
}

const SOURCE_LABEL = {
  gamemonetize: 'gamemonetize.com',
  gamepix: 'gamepix.com',
  gamedistribution: 'gamedistribution.com',
  crazygames: 'crazygames.com',
  gamearter: 'gamearter.com',
  madkid: 'madkidgames.com',
  direct: 'direct',
};

export const peek = () => cache;
/* load() has finished: the full catalogue, or the shelf after a failed fetch */
export const isLoaded = () => full || !!failed;
export const loadError = () => failed;
export const all = () => cache || adopt(STATIC.map(normalise));

/* MadKidGames blanks its games inside anyone else's page, so its copy is never
   framed, and a game nobody else hosts opens on madkidgames.com instead. */
export const theirSiteOnly = url => {
  try { return /(^|\.)madkidgames\.com$/.test(new URL(url).hostname); } catch (e) { return false; }
};
export const opensOnTheirSite = g => !!g && theirSiteOnly(g.embed)
  && !(g.alts || []).some(x => x && x.embed && !theirSiteOnly(x.embed));

/* ------------------------------------------------------------------ *
 *  sorting — memoised, so filtering never re-sorts the catalogue
 * ------------------------------------------------------------------ */
const byTitle = (a, b) => a.title.localeCompare(b.title);

const SORTS = {
  /* rows without real metrics sort after the ones that have them, alphabetically,
     rather than forming a 5,000-long block of identical "0 plays" */
  popular: (a, b) => (b.hasStats - a.hasStats) || (b.plays - a.plays) || byTitle(a, b),
  rating: (a, b) => (b.hasStats - a.hasStats) || (b.rating - a.rating) || (b.plays - a.plays) || byTitle(a, b),
  az: byTitle,
  za: (a, b) => byTitle(b, a),
  newest: (a, b) => (b.added || '').localeCompare(a.added || '') || (b.order - a.order),
  catalogue: (a, b) => a.order - b.order,
};

export const sortNames = () => Object.keys(SORTS);

/** Does any row carry a real timestamp? Nothing shows a "newest" view unless it does. */
export const hasAdded = () => all().some(g => g.added);

function sorted(key) {
  const k = SORTS[key] ? key : 'popular';
  let rows = sortCache.get(k);
  if (!rows) {
    rows = [...all()].sort(SORTS[k]);
    sortCache.set(k, rows);
  }
  return rows;
}

/* ------------------------------------------------------------------ *
 *  search
 * ------------------------------------------------------------------ */
/** Built on first use, per row, and kept — opening the page must cost nothing. */
function hayOf(g) {
  if (g.hay === undefined) {
    g.hay = `${g.title} ${g.studio} ${g.tags.join(' ')} ${g.cats.join(' ')}`.toLowerCase();
  }
  return g.hay;
}

function titleLow(g) {
  if (g.tlow === undefined) g.tlow = g.title.toLowerCase();
  return g.tlow;
}

/** 0 = no match. Higher is a better match, so the best titles lead the page. */
function rank(g, low) {
  const t = titleLow(g);
  if (t === low) return 6;
  if (t.startsWith(low)) return 5;
  const i = t.indexOf(low);
  if (i > 0) return t[i - 1] === ' ' ? 4 : 3;
  return hayOf(g).includes(low) ? 1 : 0;
}

/* ------------------------------------------------------------------ *
 *  typo-tolerant search (Static Play) — see core/fuzzy.js
 * ------------------------------------------------------------------ */
function titleIndex() {
  const rows = all();
  if (!fuzzyIx || fuzzyIx.rows !== rows) fuzzyIx = createIndex(rows, { title: g => g.title, hay: hayOf });
  return fuzzyIx;
}

/**
 * search(q, {limit}) -> { hits: [{row, tier, score}], title, hay, fuzzy, total, suggestion, ms }
 * Exact and prefix title matches first, then tag / studio / category matches
 * (what query({q}) finds), then close spellings — which lead, with a
 * "Did you mean" suggestion, when no title matches the words as typed.
 */
export const search = (q, opts) => titleIndex().search(q, opts);
/** Build the search index now (on an idle moment), so the first typo costs nothing extra. */
export const warmSearch = () => { titleIndex().warm(); };

/* ------------------------------------------------------------------ *
 *  query
 * ------------------------------------------------------------------ */
/**
 * query({category,q,sort,page,perPage,ids,source,tag,statsOnly,exclude})
 *   -> {items,total,page,pages,perPage}
 *
 * `ids` asks for an explicit ordered subset (favourites, recently played) and
 * keeps that order — the caller already knows the order it wants.
 */
export function query(opts = {}) {
  const {
    category = 'all', q = '', sort = 'popular', page = 1, perPage = 60,
    ids = null, source = '', tag = '', statsOnly = false, exclude = null,
  } = opts;

  const skip = exclude
    ? (exclude instanceof Set ? exclude : new Set(exclude))
    : null;
  const low = String(q || '').trim().toLowerCase();
  const tagLow = String(tag || '').trim().toLowerCase();

  let items;
  if (ids) {
    items = [];
    for (const id of ids) {
      const g = byId(id);
      if (g) items.push(g);
    }
  } else {
    items = sorted(sort);
  }

  const wanted = g =>
    (category === 'all' || (category === 'featured' ? g.curated : g.cats.includes(category)))
    && (!source || g.source === source)
    && (!tagLow || g.tags.some(t => t.toLowerCase() === tagLow))
    && (!statsOnly || g.hasStats)
    && (!skip || !skip.has(g.id))
    && (!low || rank(g, low) > 0);

  /* Filtering a pre-sorted array leaves it sorted, which is the whole point of
     sortCache: no query after the first re-sorts the catalogue. */
  items = items.filter(wanted);

  if (low && !ids) {
    /* Only a search reorders, and only over the (small) matching subset. */
    const base = SORTS[sort] || SORTS.popular;
    items.sort((a, b) => rank(b, low) - rank(a, low) || base(a, b));
  }

  const total = items.length;
  const per = Math.max(1, perPage);
  const pages = Math.max(1, Math.ceil(total / per));
  const p = Math.min(Math.max(1, page), pages);
  return { items: items.slice((p - 1) * per, p * per), total, page: p, pages, perPage: per };
}

export const byId = id => (index ? index.get(id) : all().find(g => g.id === id)) || null;

/** Ordered lookup that silently drops ids no longer in the catalogue. */
export function byIds(list) {
  const out = [];
  for (const id of list || []) {
    const g = byId(id);
    if (g) out.push(g);
  }
  return out;
}

/** Live counts per category, for the filter chips. Memoised per catalogue. */
export function counts() {
  if (countCache) return countCache;
  const m = new Map();
  for (const g of all()) for (const c of g.cats) m.set(c, (m.get(c) || 0) + 1);
  m.set('all', all().length);
  m.set('featured', all().reduce((n, g) => n + (g.curated ? 1 : 0), 0));
  countCache = m;
  return m;
}

const META = new Map(GAME_CATEGORIES.map(c => [c.id, c]));
/* Categories the feeds use that catalog.js has no entry for. Kept here rather
   than in catalog.js so the shared catalogue file stays untouched. */
const EXTRA_META = {
  survival: { id: 'survival', name: 'Survival', icon: 'droplet' },
};

export function catMeta(id) {
  return META.get(id) || EXTRA_META[id] || { id, name: titleCase(id), icon: 'tag' };
}

const titleCase = s => String(s).charAt(0).toUpperCase() + String(s).slice(1);

/**
 * Every category that actually has games, biggest first, with its real count.
 * Nothing renders a chip for a category the catalogue cannot fill.
 */
export function categories() {
  if (catCache) return catCache;
  const c = counts();
  const rows = [];
  for (const [id, n] of c) {
    if (id === 'all' || id === 'featured' || !n) continue;
    rows.push({ ...catMeta(id), count: n });
  }
  rows.sort((a, b) => b.count - a.count);
  catCache = rows;
  return rows;
}

/**
 * Related games: shared categories first, then shared tags, then the rest of
 * the primary category. Scored rather than "same category, top plays", so a
 * two-player racing game leads with other two-player racing games.
 */
export function related(game, n = 14) {
  if (!game) return [];
  const cats = new Set(game.cats);
  const tags = new Set(game.tags.map(t => t.toLowerCase()));
  const pool = [];
  for (const g of sorted('popular')) {
    if (g.id === game.id) continue;
    let score = 0;
    for (const c of g.cats) if (cats.has(c)) score += 2;
    if (!score) continue;
    for (const t of g.tags) if (tags.has(t.toLowerCase())) score += 3;
    if (g.source === game.source) score += 0.5;
    pool.push([score, g]);
    /* `sorted('popular')` is already the order we want inside a score band, so a
       generous cap keeps this O(cap) instead of O(catalogue log catalogue). */
    if (pool.length >= n * 30) break;
  }
  pool.sort((a, b) => b[0] - a[0]);
  return pool.slice(0, n).map(p => p[1]);
}

/** Real, countable facts about the loaded catalogue — nothing derived or guessed. */
export function stats() {
  if (statCache) return statCache;
  const rows = all();
  const sources = new Map();
  let withStats = 0;
  for (const g of rows) {
    sources.set(g.source, (sources.get(g.source) || 0) + 1);
    if (g.hasStats) withStats++;
  }
  statCache = {
    total: rows.length,
    withStats,
    curated: counts().get('featured') || 0,
    categories: categories().length,
    sources: [...sources.entries()].sort((a, b) => b[1] - a[1]),
    fallback: !!failed,
  };
  return statCache;
}

export default {
  load, peek, isLoaded, loadError, all, query, byId, byIds, counts,
  categories, catMeta, related, stats, sortNames, hasAdded, search, warmSearch,
  theirSiteOnly, opensOnTheirSite,
};
